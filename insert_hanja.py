place_map = {}

# 1. "고당동(古堂洞)" 처럼 괄호가 포함된 형식 추출
for match in re.finditer(r'([가-힣0-9]+(?:동\d*가|로\d*가)?|[가-힣0-9]+)\(([一-龥]+)\)', RAW_DATA):
    place_map[match.group(1)] = match.group(2)

# 2. 공백/탭으로 구분된 형식 추출
for line in RAW_DATA.split('\n'):
    line_clean = re.sub(r'[가-힣0-9]+\([一-龥]+\)', '', line)
    tokens = re.split(r'\s+', line_clean.strip())
    
    for i in range(len(tokens) - 1):
        if re.match(r'^[가-힣0-9]+$', tokens[i]) and re.match(r'^[一-龥]+$', tokens[i+1]):
            place_map[tokens[i]] = tokens[i+1]

def get_hanja_categories(hanja_name):
    """
    한자 문자열에서 행정구역 접미사를 제거한 뒤,
    남은 지명의 앞글자와 뒷글자를 각각 추출하여
    'X- 형식의 지명', '-X 형식의 지명' 두 가지 카테고리를 모두 반환합니다.
    """
    cleaned = re.sub(r'[廣域特別道市郡區邑面洞里街一二三四五六七八九十]+$', '', hanja_name)
    categories = []
    
    if cleaned:
        # 첫 글자 카테고리 (예: 飛- 형식의 지명)
        categories.append(f"{cleaned[0]}- 형식의 지명")
        # 마지막 글자 카테고리 (예: -川 형식의 지명)
        categories.append(f"-{cleaned[-1]} 형식의 지명")
    elif hanja_name:
        # 꼬리가 모두 잘려버린 예외 방어용
        categories.append(f"{hanja_name[0]}- 형식의 지명")
        categories.append(f"-{hanja_name[0]} 형식의 지명")
        
    # 중복 제거 (만약 1글자 지명이면 앞/뒤가 같아서 중복될 수 있음)
    return list(set(categories))

print("🚀 앞/뒤 한자 지명 카테고리 동시 자동 업데이트 시작...")

updated_count = 0

for place, hanja in place_map.items():
    filename = f"{place}.html"
    filepath = os.path.join(WIKI_PATH, filename)
    
    if not os.path.exists(filepath):
        continue
        
    target_cats = get_hanja_categories(hanja)
    if not target_cats:
        continue
        
    with open(filepath, 'r', encoding='utf-8') as f:
        html_content = f.read()
        
    # 이미 적용되어 있지 않은 카테고리만 골라내기
    cats_to_add = [cat for cat in target_cats if cat not in html_content]
    
    if not cats_to_add:
        continue
        
    match = re.search(r'(<div[^>]*class="[^"]*category-box[^"]*"[^>]*>.*?)(</div>)', html_content, re.DOTALL)
    if match:
        shutil.copy2(filepath, os.path.join(BACKUP_PATH, filename))
        
        # 여러 개의 카테고리를 연달아 붙이기
        new_cat_html = ""
        for cat in cats_to_add:
            new_cat_html += f'\n<span style="color: var(--wiki-border);">|</span> \n<a class="wiki-link" href="{cat}.html">{cat}</a> '
            
        new_html = html_content[:match.end(1)] + new_cat_html + "\n" + match.group(2) + html_content[match.end(2):]
        
        with open(filepath, 'w', encoding='utf-8') as f:
            f.write(new_html)
            
        print(f"✅ [{place}.html] 업데이트 완료: {', '.join(cats_to_add)} 추가됨")
        updated_count += 1

print(f"\n🎉 모든 작업이 완료되었습니다! 총 {updated_count}개의 행정구역 문서에 앞/뒤 한자 카테고리가 업데이트되었습니다. 🎉")