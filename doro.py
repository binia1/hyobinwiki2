def generate_html():
    navboxes = []
    lines = RAW_DATA.strip().split('\n')
    
    for line in lines:
        if not line.strip(): continue
        parts = line.split('\t')
        if len(parts) < 5: continue
            
        region_wide = parts[0].strip()
        region_local = parts[1].strip()
        color = parts[2].strip()
        logo_name = parts[3].strip()
        roads_raw = parts[4].strip()
        
        # 도로명 리스트 정렬 및 정제
        roads = sorted([r.strip() for r in roads_raw.split(',') if r.strip()])
        
        # 타이틀 결정 로직 (구 단위인지, 광역 단위인지)
        if " " in region_local and region_wide != region_local:
            # ex) 천주시 궁하구 -> 덕빈북도 천주시 / 궁하구 관내 로
            sub_splits = region_local.split()
            title_sub = f"{region_wide} {sub_splits[0]}"
            title_main = f"{sub_splits[1]} 관내 로"
        elif region_wide == region_local:
            # ex) 덕빈북도 덕빈북도 -> 덕빈북도 / 덕빈북도 관내 대로
            title_sub = region_wide
            title_main = f"{region_local} 관내 대로"
        else:
            # ex) 효빈광역시 중구 -> 효빈광역시 / 중구 관내 로
            title_sub = region_wide
            title_main = f"{region_local} 관내 로"
            
        # 초성별 그룹핑
        grouped_roads = {}
        for road in roads:
            ch = get_chosung(road)
            if ch not in grouped_roads:
                grouped_roads[ch] = []
            
            link_cls = get_link_class(road)
            grouped_roads[ch].append(f'<a href="{road}.html" class="{link_cls}">{road}</a>')
            
        # 가나다 순으로 정렬하기 위해 초성 리스트 정렬
        sorted_chosungs = sorted(grouped_roads.keys(), key=lambda x: (x == '기타', x))

        navbox_html = f"""
    <!-- {region_local} 둘러보기 틀 -->
    <div class="wiki-navbox" style="border-color: {color};">
        <div class="wiki-navbox-header" style="background-color: {color};">
            <div class="header-content">
                <img src="이미지/{logo_name}.webp" alt="로고" onerror="this.style.display='none'">
                <div>
                    <div class="title-sub">{title_sub}</div>
                    <div class="title-main">{title_main}</div>
                </div>
            </div>
        </div>
        <details open>
            <summary>[ 펼치기 · 접기 ]</summary>
            <table class="wiki-navbox-table">"""
            
        for ch in sorted_chosungs:
            roads_str = " · ".join(grouped_roads[ch])
            navbox_html += f"""
                <tr><th style="background-color:{color};">{ch}</th><td>{roads_str}</td></tr>"""
                
        navbox_html += f"""
            </table>
            <div class="wiki-navbox-footer" style="background-color: {color};">
                {title_sub.split()[0]}의 도로 틀 둘러보기
            </div>
        </details>
    </div>
"""
        navboxes.append(navbox_html)
        
    return HTML_HEADER + "".join(navboxes) + HTML_FOOTER

