import sys
import hashlib

def get_chosung(word):
    """
    한글 단어의 첫 글자에서 초성을 추출합니다.
    영문이나 숫자 등은 '기타'로 분류합니다.
    """
    if not word:
        return '기타'
    
    first_char = word[0]
    
    # 한글 가상 범위인지 확인
    if '가' <= first_char <= '힣':
        # 한글 유니코드 계산법: (문자코드 - 0xAC00) // 588 = 초성 인덱스
        idx = (ord(first_char) - ord('가')) // 588
        chosungs = ['ㄱ','ㄲ','ㄴ','ㄷ','ㄸ','ㄹ','ㅁ','ㅂ','ㅃ','ㅅ',
                    'ㅆ','ㅇ','ㅈ','ㅉ','ㅊ','ㅋ','ㅌ','ㅍ','ㅎ']
        chosung = chosungs[idx]
        
        # 쌍자음은 일반 자음으로 병합 (예: ㄲ -> ㄱ)
        merge_map = {'ㄲ':'ㄱ', 'ㄸ':'ㄷ', 'ㅃ':'ㅂ', 'ㅆ':'ㅅ', 'ㅉ':'ㅈ'}
        return merge_map.get(chosung, chosung)
    
    return '기타'

def get_link_class(road_name):
    """
    위키 문서의 존재 여부를 나타내는 빨간색/파란색 링크 클래스를 결정합니다.
    단순 텍스트 목록이므로, 해시(Hash)를 사용해 규칙적이고 고정된(Deterministic) 색상을 부여합니다.
    """
    # MD5 해시값의 정수 변환 후 3으로 나눈 나머지로 결정 (약 33% 확률로 파란 링크)
    hash_val = int(hashlib.md5(road_name.encode('utf-8')).hexdigest(), 16)
    if hash_val % 3 == 0:
        return "blue-link"
    return "red-link"

