// 💡 [추가] 이미 하드코딩된 a 태그들의 href 속성에서 언더바(_)를 띄어쓰기로 강제 치환
// 💡 [수정] 띄어쓰기 누락, 언더바 등 모든 하드코딩 링크 오류를 추적해서 진짜 주소로 고치는 함수
function fixHardcodedLinks() {
    const allLinks = document.querySelectorAll('a');
    
    allLinks.forEach(link => {
        let href = link.getAttribute('href');
        
        // href가 없거나, 외부 사이트(http)거나, 앵커(#)면 건너뜀
        if (!href || href.startsWith('http') || href.startsWith('#')) return;

        try {
            // 1. 혹시 인코딩(%ED%95...)되어 있으면 사람이 읽을 수 있게 풂
            let decodedHref = decodeURI(href);
            
            // 2. 주소에서 '.html'을 떼어내서 순수 이름만 추출 (예: "하나조노타에" 또는 "하나조노_타에")
            let rawName = decodedHref.replace(/\.html$/i, '');
            
            // 3. 띄어쓰기와 언더바를 모조리 없애고 소문자로 만든 '비교용 텍스트' 생성 (예: "하나조노타에")
            let noSpaceTarget = rawName.replace(/[\s_]+/g, '').toLowerCase();
            
            // 4. 우리의 딕셔너리(wikiLinkMap)를 다 뒤져서 진짜 주소 찾기!
            let realTargetUrl = null;
            for (let key in wikiLinkMap) {
                // 딕셔너리의 키도 띄어쓰기 싹 빼고 비교
                let noSpaceKey = key.replace(/[\s_]+/g, '').toLowerCase();
                
                if (noSpaceTarget === noSpaceKey) {
                    realTargetUrl = wikiLinkMap[key]; // 찾았다! (예: "하나조노 타에.html")
                    break;
                }
            }
            
            // 5. 진짜 주소를 찾았으면 <a> 태그의 href를 올바른 주소로 강제 교체!
            if (realTargetUrl) {
                link.setAttribute('href', encodeURI(realTargetUrl));
            }

        } catch (e) {
            // 주소 형식이 심하게 깨져있을 경우 무시
            console.warn("URL 복원 중 에러 발생:", href);
        }
    });
    
    console.log("[AutoLink] 하드코딩된 A 태그: 띄어쓰기 누락 및 언더바 완벽 교정 완료!");
}
