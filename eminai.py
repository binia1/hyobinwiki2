# 딕셔너리로 추출 (오직 '44통 198반' 등 통/반 정보만 담습니다)
df = pd.read_csv(StringIO(data_text), sep='\t')
data_dict = {}
for _, row in df.iterrows():
    dong = str(row['행정동/읍,면,동']).strip()
    tongban = str(row['행정리/통, 반개수']).strip()
    data_dict[dong] = tongban

print("=== [최종 스나이퍼] 상위 문서 파괴 원천 차단 및 정밀 주입 시작 ===")

current_dir = os.getcwd()

# 🚨 행정동 이름 -> 파일 이름 매핑
def get_target_filename(admin_dong):
    match = re.match(r'^([가-힣]+)\d+동$', admin_dong)
    if match:
        return f"{match.group(1)}동.html"
    return f"{admin_dong}.html"

# 파일별로 동 묶어주기
file_to_dongs = {}
for dong, tongban in data_dict.items():
    tf = get_target_filename(dong)
    if tf not in file_to_dongs:
        file_to_dongs[tf] = []
    file_to_dongs[tf].append((dong, tongban))

# 천주시 등 수작업 대상 문서들 (절대 안 건드림)
cheonju_dongs = ['고도동', '궁영동', '내항동', '약맥동', '유내동', '중앙동', '광정동', '관아동', '대뢰동', '마야동', '복주동', '인자읍', '천성동', '팔호동', '백로면', '엽월면', '아이동']

for target_file, dongs in file_to_dongs.items():
    file_path = os.path.join(current_dir, target_file)
    
    if not os.path.exists(file_path):
        continue

    base_name = target_file.replace('.html', '')
    if base_name in cheonju_dongs:
        continue

    with open(file_path, 'r', encoding='utf-8') as f:
        soup = BeautifulSoup(f, 'html.parser')

    modified = False

    # ---------------------------------------------------------
    # 🚨 [가장 중요한 핵심] BeautifulSoup(BS4)을 사용하여 
    # '행정동(메인) 인포박스'만 정확히 잡아냅니다.
    # 법정동 인포박스(bj-infobox, legal-dong-infobox)는 무시합니다.
    # ---------------------------------------------------------
    target_infoboxes = []
    
    # 1. aside.infobox 형태 (일반적인 메인 인포박스)
    for aside in soup.find_all('aside'):
        classes = aside.get('class', [])
        if any('infobox' in c for c in classes):
            target_infoboxes.append(aside)
            
    # 2. div.hj-infobox 형태 (평당동 등 다중 행정동 문서의 행정동 인포박스)
    for div in soup.find_all('div'):
        classes = div.get('class', [])
        if any('hj-infobox' in c for c in classes):
            target_infoboxes.append(div)

    # 추출된 각 인포박스에 대해 맞는 동네(admin_dong)를 찾아서 데이터 주입
    for infobox in target_infoboxes:
        # 이 인포박스 안에 적힌 텍스트를 쭉 읽어옵니다.
        text_content = infobox.get_text()
        
        matched_dong = None
        
        # 글자 수가 긴 동네부터 찾습니다 (중수1동이 중수동보다 먼저 매칭되도록)
        sorted_dongs = sorted([d[0] for d in dongs], key=len, reverse=True)
        for d_name in sorted_dongs:
            if d_name in text_content:
                matched_dong = d_name
                break
                
        if matched_dong:
            tongban = data_dict[matched_dong]
            
            # 이 인포박스 안에서 '하위 행정구역' 칸을 찾습니다.
            th_hawi = None
            for th in infobox.find_all('th'):
                if '하위' in th.get_text() and '행정구역' in th.get_text():
                    th_hawi = th
                    break
                    
            if th_hawi:
                # '하위 행정구역'이 이미 존재하면, 그 옆칸(td)의 내용을 **순수 통반**으로 완전히 덮어씌웁니다.
                # 이렇게 하면 "4전체 (54통 243반) (54통 243반)" 같은 쓰레기 데이터가 싹 날아가고 깨끗해집니다.
                td_hawi = th_hawi.find_next_sibling('td')
                if td_hawi:
                    td_hawi.string = tongban
                    modified = True
                    print(f"✅ [{target_file}] {matched_dong} - 쓰레기 텍스트 제거 및 통반({tongban}) 덮어쓰기 완료!")
            
            else:
                # '하위 행정구역' 줄이 없으면, '면적' 칸을 찾아서 그 윗줄에 꽂아 넣습니다.
                th_area = None
                for th in infobox.find_all('th'):
                    if '면적' in th.get_text():
                        th_area = th
                        break
                
                if th_area:
                    tr_area = th_area.find_parent('tr')
                    
                    # 새로운 tr 생성
                    new_tr = soup.new_tag('tr')
                    
                    # 새로운 th 생성 (기존 면적 th의 클래스/스타일 복사)
                    new_th = soup.new_tag('th')
                    new_th.string = "하위 행정구역"
                    if th_area.has_attr('class'): new_th['class'] = th_area['class']
                    if th_area.has_attr('style'): new_th['style'] = th_area['style']
                    
                    # 새로운 td 생성 (기존 면적 td의 클래스/스타일 복사)
                    new_td = soup.new_tag('td')
                    new_td.string = tongban
                    td_area = th_area.find_next_sibling('td')
                    if td_area:
                        if td_area.has_attr('class'): new_td['class'] = td_area['class']
                        if td_area.has_attr('style'): new_td['style'] = td_area['style']
                    
                    # 조립해서 끼워 넣기
                    new_tr.append(new_th)
                    new_tr.append(new_td)
                    tr_area.insert_before(new_tr)
                    modified = True
                    print(f"✅ [{target_file}] {matched_dong} - '하위 행정구역' 행 신설 및 통반({tongban}) 주입 완료!")

    if modified:
        # BS4로 수정한 결과를 저장 (str(soup) 사용 시 레이아웃, 줄바꿈 유지)
        html_str = str(soup)
        
        # 추가적인 텍스트 치환 작업
        if '내조동' in target_file and '1호선' in html_str:
            html_str = html_str.replace('1호선', '7호선')
        if '창전동' in target_file and '롯데몰 창전점' not in html_str:
            html_str = html_str.replace('주요 시설', '주요 시설 (애니플러스샵 창전점, 롯데몰 창전점, 뉴코아아울렛 창전점 포함)')
        if '이자동' in target_file and '이자파크몰' not in html_str:
            html_str = html_str.replace('주요 시설', '주요 시설 (이자파크몰(이자공원역) 포함)')
        if '동곡동' in target_file and '롯데마트 맥스' not in html_str:
            html_str = html_str.replace('주요 시설', '주요 시설 (롯데마트 맥스 창전점 포함)')
        if '청엽동' in target_file and '아논타워몰' not in html_str:
            html_str = html_str.replace('주요 시설', '주요 시설 (아논타워몰 포함)')

        with open(file_path, 'w', encoding='utf-8') as f:
            f.write(html_str)

